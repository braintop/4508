class MathUtils:

    @staticmethod
    def add(a, b):
        return a + b

    @staticmethod
    def subtract(a, b):
        return a - b

    @staticmethod
    def multiply(a, b):
        return a * b

    @staticmethod
    def divide(a, b):
        return a / b

print(MathUtils.add(1, 2))
print(MathUtils.subtract(1, 2))
print(MathUtils.multiply(1, 2))
print(MathUtils.divide(1, 2))







